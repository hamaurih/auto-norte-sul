-- Authentication/API/PII hardening.
-- Passwords remain managed by Supabase Auth (bcrypt hashes); never store reversible passwords.

create schema if not exists private;

create table if not exists public.auth_login_attempts (
  id bigint generated by default as identity primary key,
  identifier_hash text not null,
  ip_hash text not null,
  success boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists auth_login_attempts_identifier_created_idx
  on public.auth_login_attempts (identifier_hash, created_at desc);
create index if not exists auth_login_attempts_ip_created_idx
  on public.auth_login_attempts (ip_hash, created_at desc);

alter table public.auth_login_attempts enable row level security;
revoke all on table public.auth_login_attempts from public, anon, authenticated;
grant select, insert, delete on table public.auth_login_attempts to service_role;
revoke all on sequence public.auth_login_attempts_id_seq from public, anon, authenticated;
grant usage, select on sequence public.auth_login_attempts_id_seq to service_role;

drop policy if exists auth_login_attempts_deny_clients on public.auth_login_attempts;
create policy auth_login_attempts_deny_clients
on public.auth_login_attempts
for all
to anon, authenticated
using (false)
with check (false);

